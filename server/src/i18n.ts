/** The languages the Bigglenet speaks; English unless the request asks for Turkish first. */
export const langOf = (req: Request): 'en' | 'tr' => (/^\s*tr\b/i.test(req.headers.get('Accept-Language') ?? '') ? 'tr' : 'en');

// Each English message as a pattern, with the changing parts caught. Longest first, so "nobody
// called {1} on the Bigglenet" wins over "nobody called {1}".
let patterns: { re: RegExp; tr: string }[] | null = null;
const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** An English message in `lang`; unknown ones stay English. */
export function translate(message: string, lang: 'en' | 'tr'): string {
  if (lang === 'en') return message;
  if (TR[message]) return TR[message];
  patterns ??= Object.entries(TR)
    .filter(([en]) => /\{\d\}/.test(en))
    .sort(([a], [b]) => b.length - a.length)
    .map(([en, tr]) => ({ re: new RegExp('^' + escape(en).replace(/\\\{\d\\\}/g, '(.+?)') + '$'), tr }));
  for (const { re, tr } of patterns) {
    const m = message.match(re);
    if (m) return tr.replace(/\{(\d)\}/g, (_, i: string) => m[Number(i)] ?? '');
  }
  return message;
}

/** An error answer (fail() in http.ts), with its message in the asker's language. */
export async function translateError(res: Response, lang: 'en' | 'tr'): Promise<Response> {
  if (lang === 'en' || !res.headers.has('X-Biggle-Error') || !(res.headers.get('Content-Type') ?? '').startsWith('application/json')) return res;
  const body = (await res.json()) as { error: string; message: string };
  return new Response(JSON.stringify({ ...body, message: translate(body.message, lang) }), { status: res.status, headers: res.headers });
}
